FIELDS.forEach((row) => {
  if (row.metricId && !metricIds.has(row.metricId)) {
    throw new Error(`BESTEP class contract references unknown metric ${row.metricId}`);
  }
  if (row.temporalContractId && !temporalIds.has(row.temporalContractId)) {
    throw new Error(`BESTEP class contract references unknown temporal contract ${row.temporalContractId}`);
  }
  if (row.proposedMetricId && metricIds.has(row.proposedMetricId)) {
    throw new Error(`Proposed metric collided with the registry: ${row.proposedMetricId}`);
  }
});

