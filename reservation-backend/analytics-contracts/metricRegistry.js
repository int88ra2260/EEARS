const BY_ID = new Map(METRICS.map((row) => [row.metricId, row]));

function cloneMetric(row) {
  return {
    ...row,
    temporalContractIds: [...row.temporalContractIds],
    sourceIds: [...row.sourceIds],
    calculationReference: [...row.calculationReference],
    decisionGateIds: [...row.decisionGateIds],
    claimRestrictions: [...row.claimRestrictions],
    legacyReferences: [...row.legacyReferences],
    disambiguators: [...row.disambiguators],
  };
}

function getMetricDefinition(metricId) {
  const row = BY_ID.get(metricId);
  if (!row) {
    throw new ContractRegistryError('METRIC_NOT_FOUND', `未知的 Metric ID：${metricId}`);
  }
  return cloneMetric(row);
}

function listMetricDefinitions(filters = {}) {
  return METRICS.filter((row) => {
    if (filters.domainId && row.domainId !== filters.domainId) return false;
    if (filters.implementationStatus && row.implementationStatus !== filters.implementationStatus) return false;
    if (filters.governanceStatus && row.governanceStatus !== filters.governanceStatus) return false;
    if (filters.conflictGroup && row.conflictGroup !== filters.conflictGroup) return false;
    if (filters.legacyActive != null && row.legacyActive !== filters.legacyActive) return false;
    return true;
  }).map(cloneMetric);
}

function getMetricTemporalContracts(metricId) {
  return getMetricDefinition(metricId).temporalContractIds;
}

function getMetricDecisionGates(metricId) {
  return getMetricDefinition(metricId).decisionGateIds;
}

function getMetricLegacyReferences(metricId) {
  return getMetricDefinition(metricId).legacyReferences;
}

module.exports = {
  METRICS,
  VERSION,
  getMetricDefinition,
  listMetricDefinitions,
  getMetricTemporalContracts,
  getMetricDecisionGates,
  getMetricLegacyReferences,
};
