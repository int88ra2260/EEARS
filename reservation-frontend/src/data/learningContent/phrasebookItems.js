/**
 * @param {{ activityType?: string }} [filters]
 */
export function getPhrasebookItems(filters = {}) {
  return PHRASEBOOK_ITEMS
    .filter((item) => {
      if (!item.isActive) return false;
      if (filters.activityType && item.activityType !== filters.activityType) return false;
      return true;
    })
    .sort((a, b) => a.sortOrder - b.sortOrder);
}

/**
 * @param {string} activityType
 * @param {number} [limit]
 */
export function getQuickPrepItems(activityType, limit = 3) {
  return getPhrasebookItems({ activityType }).slice(0, limit);
}

